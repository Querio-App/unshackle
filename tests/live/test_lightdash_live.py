"""Lightdash, live: self-hosted Lightdash in Docker over the Dunder Mifflin warehouse.

1. warehouse + Lightdash up; the dataset loaded; the dbt project (tests/live/lightdash/dbt) run
   with a local dbt-postgres, then deployed with the Lightdash CLI (`lightdash deploy`)
2. admin user, organization, personal access token and project created through the API
3. charts and a dashboard uploaded as code (tests/live/lightdash/content)
4. `unshackle init / inventory / extract / build lightdash` in a temp repo
5. Ossie files and notebooks validated; parity cases compare Lightdash's own query
   results with the migrated notebook tiles, verified query and Ossie metrics; `unshackle verify`

Needs: Docker, docker-compose, Node.js (npx), and a dbt with the postgres adapter
(UNSHACKLE_LIVE_DBT=/path/to/dbt, else `dbt` on PATH). See tests/live/README.md.
"""

from __future__ import annotations

import json
import os
import secrets
import shutil
import subprocess
from pathlib import Path
from typing import Any

import httpx
import pytest
import yaml
from harness import ENABLED, LIVE, SKIP_REASON, Stack, run_unshackle, wait_for, write_case, write_csv

pytestmark = [pytest.mark.live, pytest.mark.skipif(not ENABLED, reason=SKIP_REASON)]

VERSION = os.environ.get("UNSHACKLE_LIVE_LIGHTDASH_VERSION", "3.23.1")
PORT = os.environ.get("UNSHACKLE_LIVE_LIGHTDASH_PORT", "58080")
DBT_DIR = LIVE / "lightdash" / "dbt"
CONTENT = LIVE / "lightdash" / "content"


class Lightdash:
    def __init__(self, url: str):
        self.url = url
        self.http = httpx.Client(base_url=url, timeout=120)
        self.project = ""

    def call(self, method: str, path: str, **kw: Any) -> Any:
        res = self.http.request(method, path, **kw)
        if res.status_code >= 400:
            raise AssertionError(f"{method} {path} -> {res.status_code}: {res.text[:1000]}")
        return res.json().get("results")

    def bootstrap(self) -> str:
        """First user (becomes admin), organization, personal access token. Returns the token."""
        password = "Ul-" + secrets.token_hex(12)
        self.call("POST", "/api/v1/user", json={"firstName": "Live", "lastName": "Test", "email": "admin@unshackle.test", "password": password})
        self.call("PUT", "/api/v1/org", json={"name": "Dunder Mifflin"})
        token = self.call("POST", "/api/v1/user/me/personal-access-tokens", json={"description": "unshackle live test", "expiresAt": None, "autoGenerated": False})["token"]
        self.http.cookies.clear()
        self.http.headers["Authorization"] = f"ApiKey {token}"
        return token

    def create_project(self, pg_password: str) -> str:
        # dbtConnection "none": explores are deployed by the Lightdash CLI. A "dbt" (local
        # project) connection would make Lightdash run dbt inside its amd64 image, which
        # segfaults under QEMU on arm64 hosts.
        body = {
            "name": "Dunder Mifflin", "type": "DEFAULT", "dbtVersion": "v1.10", "dbtConnection": {"type": "none"},
            "warehouseConnection": {
                "type": "postgres", "host": "warehouse", "port": 5432, "user": "unshackle", "password": pg_password,
                "dbname": "dunder_mifflin", "schema": "analytics", "sslmode": "disable",
            },
        }
        self.project = self.call("POST", "/api/v1/org/projects", json=body)["project"]["projectUuid"]
        return self.project

    def upload(self, kind: str, path: Path) -> dict[str, Any]:
        doc = yaml.safe_load(path.read_text())
        res = self.call("POST", f"/api/v1/projects/{self.project}/code/{kind}/{doc['slug']}", json=doc)
        return res[kind][0]["data"]

    def run(self, path: str, body: dict[str, Any]) -> tuple[list[str], list[list[Any]]]:
        """Run a query through Lightdash (v2 async API) and return (columns, raw rows)."""
        base = f"/api/v2/projects/{self.project}/query"
        qid = self.call("POST", f"{base}/{path}", json={**body, "context": "api"})["queryUuid"]
        get = lambda: _ready(self.call("GET", f"{base}/{qid}", params={"page": 1, "pageSize": 2500}))  # noqa: E731
        res = wait_for(get, f"query {qid}", 120, 1, retry_on=(httpx.HTTPError,))
        assert res.get("totalPageCount", 1) == 1, "more than one page of results"
        cols = list(res["columns"])
        return cols, [[(r.get(c) or {}).get("value", {}).get("raw") for c in cols] for r in res["rows"]]


def _ready(res: dict[str, Any]) -> dict[str, Any] | None:
    if res.get("status") == "error":
        raise AssertionError(f"Lightdash query failed: {res.get('error')}")
    return res if res.get("status") == "ready" else None


def _dbt(stack: Stack) -> tuple[str, dict[str, str]]:
    dbt = os.environ.get("UNSHACKLE_LIVE_DBT") or shutil.which("dbt")
    if not dbt:
        pytest.fail("needs dbt with the postgres adapter: set UNSHACKLE_LIVE_DBT or put dbt on PATH")
    env = {
        **os.environ, "UNSHACKLE_LIVE_PG_PASSWORD": stack.password, "UNSHACKLE_LIVE_PG_PORT": str(stack.pg_port),
        "PATH": f"{Path(dbt).parent}{os.pathsep}{os.environ['PATH']}", "DBT_SEND_ANONYMOUS_USAGE_STATS": "false",
    }
    return dbt, env


def _sh(cmd: list[str], env: dict[str, str], cwd: Path) -> str:
    proc = subprocess.run(cmd, env=env, cwd=cwd, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if proc.returncode != 0:
        raise AssertionError(f"{' '.join(cmd[:3])} failed:\n{proc.stdout[-5000:]}")
    return proc.stdout


def _ossie_metric_sql(repo: Path, dataset: str, time_field: str, dims: list[str]) -> tuple[str, list[str]]:
    """SQL for every metric of one Ossie dataset by month of `time_field` (+ dims), from the expressions unshackle wrote."""
    for path in sorted((repo / "semantic").glob("*.ossie.yaml")):
        for ds in yaml.safe_load(path.read_text())["datasets"]:
            if ds["name"] != dataset or not ds.get("metrics"):
                continue
            expr = {f["name"]: f["expression"]["dialects"][0]["expression"] for f in ds["fields"]}
            select = [f"cast(date_trunc('month', {expr[time_field]}) as date) as {dataset}_{time_field}_month"]
            select += [f"{expr[d]} as {dataset}_{d}" for d in dims]
            metrics = [m["name"] for m in ds["metrics"]]
            select += [f"{m['expression']['dialects'][0]['expression']} as {dataset}_{m['name']}" for m in ds["metrics"]]
            group = ", ".join(str(i + 1) for i in range(1 + len(dims)))
            return f"select {', '.join(select)}\nfrom {ds['source']}\ngroup by {group}", metrics
    raise AssertionError(f"no Ossie dataset {dataset} with metrics")


def test_lightdash_end_to_end(tmp_path: Path):
    from conftest import notebook_source
    from test_ossie import _check

    with Stack("lightdash") as stack:
        assert stack.load_data()
        dbt, dbt_env = _dbt(stack)
        target = tmp_path / "dbt-target"
        dbt_env["DBT_LOG_PATH"] = str(tmp_path / "dbt-logs")
        for step in ("run", "compile"):
            _sh([dbt, step, "--profiles-dir", ".", "--target-path", str(target)], dbt_env, DBT_DIR)

        ld = Lightdash(f"http://localhost:{PORT}")
        try:
            wait_for(lambda: ld.call("GET", "/api/v1/health")["healthy"], "Lightdash health", 600, 5)
        except TimeoutError:
            raise AssertionError("Lightdash did not come up:\n" + stack.logs("lightdash")) from None
        token = ld.bootstrap()
        project = ld.create_project(stack.password)

        cli = os.environ.get("UNSHACKLE_LIVE_LIGHTDASH_CLI", "").split() or ["npx", "--yes", f"@lightdash/cli@{VERSION}"]
        # A throwaway HOME keeps the CLI's login config out of the real one; npx keeps its usual cache.
        cli_env = {**dbt_env, "HOME": str(tmp_path / "home"), "npm_config_cache": os.environ.get("npm_config_cache") or str(Path.home() / ".npm"),
                   "CI": "true", "LIGHTDASH_URL": ld.url, "LIGHTDASH_API_KEY": token}
        out = _sh([*cli, "deploy", "--project", project, "--project-dir", ".", "--profiles-dir", ".", "--target-path", str(target),
                   "--skip-dbt-compile", "--non-interactive"], cli_env, DBT_DIR)
        assert "explores deployed" in out, out
        explores = ld.call("GET", f"/api/v1/projects/{project}/explores")
        assert {e["name"] for e in explores} == {"orders", "accounts", "products", "shippings", "reviews"}
        assert not [e for e in explores if e.get("errors")]

        charts = {p.stem: ld.upload("charts", p) for p in sorted((CONTENT / "charts").glob("*.yml"))}
        dashboards = [ld.upload("dashboards", p) for p in sorted((CONTENT / "dashboards").glob("*.yml"))]
        assert len(charts) >= 2 and dashboards

        # --- unshackle, as a user would run it
        repo = tmp_path / "repo"
        env = {"LIGHTDASH_URL": ld.url, "LIGHTDASH_API_KEY": token, "LIGHTDASH_PROJECT": project}
        run_unshackle(repo, "init")  # no warehouse type set: build reads it from the export
        run_unshackle(repo, "inventory", "lightdash", env=env)
        run_unshackle(repo, "extract", "lightdash", env=env)
        assert json.loads((repo / "migration/raw/lightdash/_errors.json").read_text()) == []
        print(run_unshackle(repo, "build", "lightdash"))

        docs = {p.name: yaml.safe_load(p.read_text()) for p in sorted((repo / "semantic").glob("*.ossie.yaml"))}
        assert all('"warehouse": "postgres"' in p.read_text() for p in (repo / "semantic").glob("*.ossie.yaml"))
        assert {"orders.ossie.yaml", "reviews.ossie.yaml"} <= set(docs)
        for doc in docs.values():
            _check(doc)
        rels = {frozenset((r["from"], r["to"])) for d in docs.values() for r in d.get("relationships", [])}
        for path in (repo / "migration/raw/lightdash/explores").glob("[!_]*.json"):
            explore = json.loads(path.read_text())
            for j in explore.get("joinedTables", []):
                assert frozenset((explore["baseTable"], j["table"])) in rels, f"join {explore['baseTable']} -> {j['table']} missing from Ossie"
        notebook = repo / "notebooks" / "sales-overview.ipynb"
        text = notebook_source(notebook)
        assert "TODO(unshackle)" not in text
        assert (repo / "queries" / "average-rating-by-month.sql").exists()

        # --- parity: Lightdash's own results vs the migrated SQL on the same warehouse
        data = repo / "migration" / "parity" / "data"
        for slug, tile in (("monthly-revenue", "monthly_revenue"), ("revenue-by-region", "revenue_by_region"), ("total-revenue", "total_revenue")):
            cols, rows = ld.run("chart", {"chartUuid": charts[slug]["uuid"]})
            write_csv(data / f"{slug}.csv", cols, rows)
            write_case(repo, slug, {
                "name": f"Sales overview - {charts[slug]['name']}",
                "source": {"csv": f"migration/parity/data/{slug}.csv"},
                "target": {"notebook": "notebooks/sales-overview.ipynb", "tile": tile},
                "keys": [c for c in cols if c in charts[slug]["metricQuery"]["dimensions"]],
                "tolerance": 0.0001,
            })
        slug = "average-rating-by-month"
        cols, rows = ld.run("chart", {"chartUuid": charts[slug]["uuid"]})
        write_csv(data / f"{slug}.csv", cols, rows)
        sql = "\n".join(l for l in (repo / "queries" / f"{slug}.sql").read_text().splitlines() if not l.startswith("--"))
        write_case(repo, slug, {
            "name": "Verified query - Average rating by month", "source": {"csv": f"migration/parity/data/{slug}.csv"},
            "target": {"sql": sql}, "keys": ["reviews_reviewed_at_month"],
        })
        for dataset, time_field, dims in (("orders", "purchased_at", ["status"]), ("reviews", "reviewed_at", [])):
            sql, metrics = _ossie_metric_sql(repo, dataset, time_field, dims)
            keys = [f"{dataset}_{time_field}_month", *(f"{dataset}_{d}" for d in dims)]
            query = {"exploreName": dataset, "dimensions": keys, "metrics": [f"{dataset}_{m}" for m in metrics], "filters": {},
                     "sorts": [], "limit": 5000, "tableCalculations": [], "additionalMetrics": []}
            cols, rows = ld.run("metric-query", {"query": query})
            write_csv(data / f"{dataset}-metrics.csv", cols, rows)
            write_case(repo, f"{dataset}-metrics", {
                "name": f"Ossie metrics - {dataset} ({', '.join(metrics)}) by month",
                "source": {"csv": f"migration/parity/data/{dataset}-metrics.csv"}, "target": {"sql": sql}, "keys": keys,
            })

        out = run_unshackle(repo, "verify", env={"UNSHACKLE_WAREHOUSE_URL": stack.warehouse_url}, check=False)
        print(out)
        results = json.loads((repo / "migration" / "parity" / "results.json").read_text())
        assert len(results) == 6
        assert all(r["status"] == "pass" for r in results), out
