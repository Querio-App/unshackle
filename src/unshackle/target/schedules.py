"""Declarative delivery specifications. Execution and sending belong to the user's orchestrator."""

from dataclasses import asdict

from unshackle.ir import Bundle, join_todos, slugify, todo_reasons
from unshackle.target.files import one_line_comment, unique_rel
from unshackle.target.layout import Layout
from unshackle.target.notebooks import parameter_names
from unshackle.target.semantic import dump_yaml


def render(bundle: Bundle, layout: Layout, notebook_paths: dict[str, str]) -> dict[str, str]:
    files = {}
    for schedule in bundle.schedules:
        doc = asdict(schedule)
        doc["source"] = doc.pop("source_ref")
        doc["notebook"] = notebook_paths.get(schedule.dashboard_ref)
        dashboard = next((d for d in bundle.dashboards if d.source_ref == schedule.dashboard_ref), None)
        names = parameter_names(dashboard) if dashboard else {}
        doc["parameters"] = {names[k]: v for k, v in schedule.parameters.items() if k in names}
        for binding in doc["parameter_bindings"]:
            binding["notebook_names"] = [names[n] for n in binding["filter_names"] if n in names]
        if not doc["notebook"]:
            doc["todo"] = join_todos([doc["todo"], "source dashboard has no migrated notebook; resolve its reference"])
        reasons = todo_reasons(doc["todo"])
        for channel in schedule.channels:
            reasons += [f"{channel.source_ref or channel.type}: {r}" for r in todo_reasons(channel.todo)]
        text = "# Generated by unshackle. Delivery specification only; no scheduler or sender is installed.\n"
        text += "".join(f"# TODO(unshackle): {one_line_comment(r)}\n" for r in reasons)
        text += dump_yaml(doc)
        rel = layout.rel("schedules", f"{slugify(schedule.source_ref)}.yml")
        files[unique_rel(files, rel)] = text
    return files
