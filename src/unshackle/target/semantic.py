"""MetricFlow semantic layer YAML: one file per semantic model, plus _<tool>_metrics.yml for the rest.

Output must pass `dbt parse` (dbt >= 1.9) as written, so anything that isn't
finished is never emitted as YAML. It goes into a commented-out block under a
`# TODO(unshackle): ...` line in the same file instead:

  - dimensions/measures/metrics with a `todo`, or with leftover Jinja/Liquid
  - metrics missing required params, or depending on something that isn't emitted
  - measures on a model with no time dimension (MetricFlow needs one)

Other rules: reserved dimension names (month, year, metric_time...) are
prefixed with the model name, models without a primary entity get
`primary_entity`, and duplicate metric labels are made unique.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

import yaml

from unshackle.ir import Bundle, Metric, SemanticModel, snake
from unshackle.target.layout import Layout

HEADER = "# Generated by unshackle from {tool}. Edit freely: re-runs keep hand edits.\n"
RESERVED = {
    "metric_time",
    "nanosecond",
    "microsecond",
    "millisecond",
    "second",
    "minute",
    "hour",
    "day",
    "week",
    "month",
    "quarter",
    "year",
}


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.Node:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def dump_yaml(obj: Any) -> str:
    return yaml.dump(obj, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def _clean(d: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in d.items() if v not in ("", None, [], {})}


def _mf(value: str) -> str:
    """A MetricFlow element name: snake_case, starting with a letter."""
    name = snake(value)
    return f"n_{name}" if name[:1].isdigit() else name


def _unique(name: str, used: set[str]) -> str:
    out, n = name, 2
    while out in used:
        out, n = f"{name}_{n}", n + 1
    used.add(out)
    return out


def _has_jinja(value: str) -> bool:
    return "{{" in value or "{%" in value or "{#" in value


def _text(value: str) -> str:
    """Descriptions and labels are rendered by dbt as Jinja: protect source text."""
    return f"{{% raw %}}{value}{{% endraw %}}" if value and _has_jinja(value) else value


def _one_line(value: str) -> str:
    return " ".join(str(value).split())


@dataclass
class _Pending:
    kind: str
    name: str
    reason: str
    body: dict[str, Any]


@dataclass
class _FileDoc:
    doc: dict[str, Any] = field(default_factory=dict)
    pending: list[_Pending] = field(default_factory=list)

    def render(self, header: str) -> str:
        out = header
        if self.doc:
            out += dump_yaml(self.doc)
        for p in self.pending:
            out += f"\n# TODO(unshackle): {p.kind} {p.name}: {_one_line(p.reason)}\n"
            block = dump_yaml({p.kind + "s": [p.body]})
            out += "".join(f"#   {line}\n" for line in block.splitlines())
        return out


def _model_ref(model: SemanticModel, layout: Layout) -> dict[str, Any]:
    table = model.table
    if layout.is_dbt:
        return {"model": f"ref('{table.split('.')[-1]}')"}
    parts = table.split(".")
    relation: dict[str, str] = {"alias": parts[-1]}
    if len(parts) >= 2:
        relation["schema_name"] = parts[-2]
    if len(parts) >= 3:
        relation["database"] = parts[-3]
    return {"node_relation": relation}


def _reason(todo: str, language: str, expression: str) -> str:
    src = f" [{language}] {expression}" if expression and language else f" {expression}" if expression else ""
    return f"{todo}{src}"


@dataclass
class _Names:
    """Project-wide names, so MetricFlow accepts them: each element name keeps one
    type (entity, dimension, measure) across every semantic model, measure names
    are unique, and metric references resolve to the names actually written."""

    types: dict[str, str] = field(default_factory=dict)
    dims: dict[str, str] = field(default_factory=dict)
    measures: dict[tuple[str, str], str] = field(default_factory=dict)
    global_measures: set[str] = field(default_factory=set)
    metric_raw: dict[str, str] = field(default_factory=dict)
    metric_snake: dict[str, str] = field(default_factory=dict)
    entities: dict[str, str] = field(default_factory=dict)

    def entity(self, raw: str) -> str:
        base = _mf(raw)
        return self.entities.get(base, base)

    def element(self, raw: str, kind: str, model: str, used: set[str]) -> str:
        base = _mf(raw)
        name = base
        clash = self.types.get(base) not in (None, kind)
        if base in RESERVED or len(base) < 2 or clash or (kind == "measure" and base in self.global_measures):
            name = f"{model}_{base}"
        taken = used | self.global_measures if kind == "measure" else used
        name = _unique(name, taken)
        used.add(name)
        self.types.setdefault(name, kind)
        return name

    def metric(self, ref: str) -> str:
        if not ref:
            return ""
        if ref in self.metric_raw:
            return self.metric_raw[ref]
        return self.metric_snake.get(_mf(ref), _mf(ref))


def _col(raw: str) -> str:
    return raw if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", raw) else '"' + raw.replace('"', '""') + '"'


def _render_model(model: SemanticModel, layout: Layout, fd: _FileDoc, names: _Names) -> tuple[dict[str, Any], set[str]]:
    """Return (model yaml, names of measures emitted)."""
    name = _mf(model.name)
    out: dict[str, Any] = {"name": name}
    if model.description:
        out["description"] = _text(model.description)
    out.update(_model_ref(model, layout))
    used: set[str] = {names.entity(e.name) for e in model.entities}

    dims, time_dims = [], []
    default_dim = ""
    for d in model.dimensions:
        base = _mf(d.name)
        dname = names.element(d.name, "dimension", name, used)
        expr = d.expr
        if dname != snake(d.name) and not expr:
            expr = _col(d.name)
        if dname != base:
            names.dims[base] = dname
        if model.default_time_dimension and snake(model.default_time_dimension) == snake(d.name):
            default_dim = dname
        item = _clean(
            {
                "name": dname,
                "type": d.type,
                "label": _text(d.label),
                "description": _text(d.description),
                "expr": expr or None,
            }
        )
        if d.type == "time":
            item["type_params"] = {"time_granularity": d.time_granularity or "day"}
        if d.todo or _has_jinja(d.expr):
            reason = d.todo or "expression still has template code"
            fd.pending.append(_Pending("dimension", f"{name}.{dname}", _reason(reason, d.source_language, d.source_expression or d.expr), item))
            continue
        dims.append(item)
        if d.type == "time":
            time_dims.append(dname)

    # the source's declared default, or the only time dimension; never a guess among several
    agg_time = default_dim if default_dim in time_dims else (time_dims[0] if len(time_dims) == 1 else "")
    measures, emitted = [], set()
    for m in model.measures:
        mname = names.element(m.name, "measure", name, used)
        expr = m.expr
        if mname != snake(m.name) and not expr:
            expr = _col(m.name)
        names.measures.setdefault((name, m.name), mname)
        names.measures.setdefault((name, _mf(m.name)), mname)
        item = _clean(
            {
                "name": mname,
                "agg": m.agg,
                "expr": expr or None,
                "label": _text(m.label),
                "description": _text(m.description),
                "agg_params": m.agg_params,
            }
        )
        if m.todo or _has_jinja(m.expr):
            reason = m.todo or "expression still has template code"
            fd.pending.append(_Pending("measure", f"{name}.{mname}", _reason(reason, m.source_language, m.source_expression or m.expr), item))
            continue
        if not time_dims:
            fd.pending.append(
                _Pending(
                    "measure",
                    f"{name}.{mname}",
                    "MetricFlow needs a time dimension on this model for its measures: add one and set defaults.agg_time_dimension",
                    item,
                )
            )
            continue
        if not agg_time:
            fd.pending.append(
                _Pending(
                    "measure",
                    f"{name}.{mname}",
                    "the source declares no default time dimension; set defaults.agg_time_dimension to one of "
                    + ", ".join(time_dims),
                    item,
                )
            )
            continue
        measures.append(item)
        emitted.add(mname)
        names.global_measures.add(mname)

    if measures:
        out["defaults"] = {"agg_time_dimension": agg_time}
    if not any(e.type == "primary" for e in model.entities):
        out["primary_entity"] = names.entity(name)
    if model.entities:
        out["entities"] = [
            _clean({"name": names.entity(e.name), "type": e.type, "expr": e.expr or (_mf(e.name) if names.entity(e.name) != _mf(e.name) else "")})
            for e in model.entities
        ]
    if dims:
        out["dimensions"] = dims
    if measures:
        out["measures"] = measures
    return out, emitted


def _rewrite_filter(text: str, names: _Names) -> str:
    if not text or not (names.dims or names.entities):
        return text

    def sub(m: re.Match) -> str:
        return f"{m.group(1)}{names.entity(m.group(2))}__{names.dims.get(m.group(3), m.group(3))}{m.group(4)}"

    text = re.sub(r"((?:Dimension|TimeDimension)\(')(\w+?)__(\w+)(')", sub, text)
    return re.sub(r"(Entity\(')(\w+)(')", lambda m: f"{m.group(1)}{names.entity(m.group(2))}{m.group(3)}", text)


def _measure_name(metric: Metric, names: _Names) -> str:
    if not metric.measure:
        return ""
    model = _mf(metric.semantic_model) if metric.semantic_model else ""
    for key in ((model, metric.measure), (model, _mf(metric.measure))):
        if key in names.measures:
            return names.measures[key]
    owners = [v for (mod, raw), v in names.measures.items() if raw == metric.measure]
    return owners[0] if len(set(owners)) == 1 else _mf(metric.measure)


def _derived_expr(metric: Metric, names: _Names) -> str:
    expr = metric.expr
    for ref in metric.metrics:
        final = names.metric(ref)
        for old in {ref, snake(ref)}:
            if old and old != final:
                expr = re.sub(rf"(?<![\w]){re.escape(old)}(?![\w])", final, expr)
    return expr


def _metric_body(metric: Metric, names: _Names, name: str) -> dict[str, Any]:
    params: dict[str, Any] = {}
    if metric.type in ("simple", "cumulative"):
        params["measure"] = _measure_name(metric, names) or None
    if metric.type == "cumulative":
        cum = _clean({"window": metric.window, "grain_to_date": metric.grain_to_date})
        if cum:
            params["cumulative_type_params"] = cum
    if metric.type == "ratio":
        params["numerator"] = names.metric(metric.numerator) or None
        params["denominator"] = names.metric(metric.denominator) or None
    if metric.type == "derived":
        params["expr"] = _derived_expr(metric, names) or None
        params["metrics"] = [_clean({"name": names.metric(n), "offset_window": metric.offsets.get(n, "")}) for n in metric.metrics]
    body = _clean(
        {
            "name": name,
            "label": _text(metric.label or metric.name),
            "description": _text(metric.description),
            "type": metric.type,
            "type_params": _clean(params),
            "filter": _rewrite_filter(metric.filter, names),
        }
    )
    return body


def _missing(metric: Metric, measures: set[str], metrics: set[str], names: _Names) -> str:
    """Why this metric can't be emitted yet, or '' if it can."""
    if metric.todo:
        return _reason(metric.todo, metric.source_language, metric.source_expression)
    if metric.filter and "{%" in metric.filter:
        return "filter still has template code"
    if metric.type in ("simple", "cumulative"):
        m = _measure_name(metric, names)
        if not m:
            return "no measure"
        if m not in measures:
            return f"measure {m} is not migrated yet"
    if metric.type == "ratio":
        for side in (metric.numerator, metric.denominator):
            s = names.metric(side)
            if not s:
                return "ratio needs a numerator and a denominator"
            if s not in metrics:
                return f"depends on metric {s}, which is not migrated yet"
    if metric.type == "derived":
        if not metric.expr or not metric.metrics:
            return "derived metric needs an expr and input metrics"
        for n in metric.metrics:
            if names.metric(n) not in metrics:
                return f"depends on metric {names.metric(n)}, which is not migrated yet"
    if metric.type == "conversion":
        return "conversion metrics need manual setup"
    return ""


def _implied_metrics(bundle: Bundle) -> list[Metric]:
    """Ratio and derived metrics reference metrics, not measures: add simple metrics for bare measures."""
    names = {m.name for m in bundle.metrics} | {snake(m.name) for m in bundle.metrics}
    owner: dict[str, str] = {}
    for sm in bundle.semantic_models:
        for ms in sm.measures:
            owner.setdefault(ms.name, sm.name)
            owner.setdefault(snake(ms.name), sm.name)
    extra: list[Metric] = []
    for m in bundle.metrics:
        refs = [m.numerator, m.denominator] if m.type == "ratio" else list(m.metrics) if m.type == "derived" else []
        for ref in refs:
            if ref and ref not in names and snake(ref) not in names and ref in owner:
                extra.append(Metric(name=ref, measure=ref, semantic_model=owner[ref], description=f"Implied by {m.name}."))
                names |= {ref, snake(ref)}
    return extra


def render(bundle: Bundle, layout: Layout, taken: dict[str, str] | None = None) -> dict[str, str]:
    """Return {relative path: file content}. `taken` maps element names other tools' files already use to their type."""
    header = HEADER.format(tool=bundle.tool)
    model_names = {_mf(m.name) for m in bundle.semantic_models}
    docs: dict[str, _FileDoc] = {}
    names = _Names(types=dict(taken or {}))
    raw_entities = []
    for model in bundle.semantic_models:
        raw_entities += [_mf(e.name) for e in model.entities]
        if not any(e.type == "primary" for e in model.entities):
            raw_entities.append(_mf(model.name))
    for base in raw_entities:
        if names.types.get(base) not in (None, "entity") and base not in names.entities:
            names.entities[base] = _unique(f"{base}_entity", set(names.types))
    for base in raw_entities:
        names.types.setdefault(names.entity(base), "entity")
    measures: set[str] = set()
    for model in bundle.semantic_models:
        fd = docs.setdefault(_mf(model.name), _FileDoc())
        if model.todo:
            rendered, _ = _render_model(model, layout, _FileDoc(), _Names(types=dict(names.types)))
            fd.pending.append(_Pending("semantic_model", rendered["name"], model.todo, rendered))
            continue
        rendered, emitted = _render_model(model, layout, fd, names)
        fd.doc.setdefault("semantic_models", []).append(rendered)
        measures |= emitted

    metrics = list(bundle.metrics) + _implied_metrics(bundle)
    used_names: set[str] = set()
    metric_names = []
    for m in metrics:
        base = _mf(m.name)
        if base in RESERVED or len(base) < 2:
            base = f"metric_{base}"
        final = _unique(base, used_names)
        metric_names.append(final)
        names.metric_raw.setdefault(m.name, final)
        names.metric_snake.setdefault(_mf(m.name), final)
    ok: set[str] = set()
    remaining = list(zip(metrics, metric_names))
    progress = True
    while progress:
        progress = False
        for m, n in list(remaining):
            if not _missing(m, measures, ok, names):
                ok.add(n)
                remaining.remove((m, n))
                progress = True

    labels: dict[str, int] = {}
    for metric, name in zip(metrics, metric_names):
        key = _mf(metric.semantic_model) if metric.semantic_model else ""
        fd = docs.setdefault(key if key in model_names else f"_{bundle.tool}_metrics", _FileDoc())
        body = _metric_body(metric, names, name)
        if name in ok:
            label = body.get("label", name)
            if label in labels:
                labels[label] += 1
                body["label"] = f"{label} ({key or bundle.tool})" if labels[label] == 2 else f"{label} ({labels[label]})"
            else:
                labels[label] = 1
            fd.doc.setdefault("metrics", []).append(body)
        else:
            fd.pending.append(_Pending("metric", name, _missing(metric, measures, ok, names), body))

    return {layout.rel("semantic", f"{fname}.yml"): fd.render(header) for fname, fd in docs.items()}
