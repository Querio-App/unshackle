"""Permissions: Cedar schema + policies, and row filters in their own YAML file.

Cedar decides allow/deny on Datasource, Table, Column, Metric and Notebook.
Row-level rules (Tableau user filters, Looker access_filter, Power BI RLS roles)
live in row_filters.yml and are applied as SQL predicates at query time.
"""

from __future__ import annotations

import json

import yaml

from unshackle.ir import Bundle, Permission, Table, slugify, snake, todo_reasons
from unshackle.target.layout import Layout
from unshackle.target.semantic import dump_yaml

CEDAR_SCHEMA = """\
entity Group;
entity User in [Group] {
  email: String,
};
entity Datasource;
entity Table in [Datasource];
entity Column in [Table];
entity Metric in [Datasource];
entity Notebook;

action "view" appliesTo {
  principal: [User],
  resource: [Notebook, Metric, Datasource, Table, Column],
};
action "query" appliesTo {
  principal: [User],
  resource: [Datasource, Table, Column, Metric],
};
action "edit" appliesTo {
  principal: [User],
  resource: [Notebook, Metric],
};
"""


def _principal(p: str) -> str:
    if p in ("*", "all", ""):
        return "principal"
    kind, _, name = p.partition(":")
    if not name:
        kind, name = "group", kind
    entity = "User" if kind.lower() == "user" else "Group"
    op = "==" if entity == "User" else "in"
    return f"principal {op} {entity}::{json.dumps(name)}"


class _Ids:
    """Canonical resource ids: Table "<datasource>.<schema>.<table>", Column "<table id>.<column>"."""

    def __init__(self, bundle: Bundle):
        self.default = bundle.datasource
        self.tables: dict[str, list[Table]] = {}
        for t in bundle.tables:
            self.tables.setdefault(t.name.lower(), []).append(t)

    def _table(self, parts: list[str]) -> str:
        name = parts[-1]
        found = self.tables.get(name.lower(), [])
        if len(parts) >= 2 and len(found) > 1:
            found = [t for t in found if t.schema.lower() == parts[-2].lower()] or found
        if found:
            from unshackle.target.files import safe_segment

            t = found[0]
            return ".".join(safe_segment(x) for x in (t.datasource or self.default, t.schema or "main", t.name))
        if len(parts) >= 3:
            return ".".join(parts[-3:])
        if len(parts) == 2:
            return f"{self.default}.{parts[0]}.{parts[1]}"
        return f"{self.default}.main.{name}"

    def table(self, rid: str) -> str:
        return self._table([p for p in rid.split(".") if p]) if rid else rid

    def resource(self, kind: str, rid: str) -> str:
        if not rid:
            return rid
        parts = [p for p in rid.split(".") if p]
        if kind == "Column" and len(parts) >= 2:
            return f"{self._table(parts[:-1])}.{parts[-1]}"
        if kind == "Table":
            return self._table(parts)
        if kind == "Metric":
            return snake(rid)
        if kind == "Notebook":
            return slugify(rid)
        return rid


def render_permission(p: Permission) -> str:
    lines = []
    if p.source_ref or p.source_expression:
        src = " ".join(f"{p.source_ref} {p.source_expression}".split())
        lines.append(f"// source: {src}")
    lines += [f"// TODO(unshackle): {r}" for r in todo_reasons(p.todo)]
    resource = f"resource in {p.resource_type}::{json.dumps(p.resource_id)}" if p.resource_id else "resource"
    body = f"{p.effect} (\n  {_principal(p.principal)},\n  action == Action::{json.dumps(p.action)},\n  {resource}\n)"
    if p.condition:
        body += f"\nwhen {{ {p.condition} }}"
    lines.append(body + ";")
    return "\n".join(lines)


def policy_files(bundle: Bundle, layout: Layout) -> dict[str, str]:
    files: dict[str, str] = {}
    if bundle.permissions or bundle.row_filters:
        files[layout.rel("policies", "schema.cedarschema")] = CEDAR_SCHEMA
    ids = _Ids(bundle)
    if bundle.permissions:
        for p in bundle.permissions:
            p.resource_id = ids.resource(p.resource_type, p.resource_id)
        header = f"// Generated by unshackle from {bundle.tool}. Review before enforcing.\n\n"
        files[layout.rel("policies", f"{slugify(bundle.tool)}.cedar")] = header + "\n\n".join(
            render_permission(p) for p in bundle.permissions
        ) + "\n"
    if bundle.row_filters:
        rows = []
        for rf in bundle.row_filters:
            item = {
                "name": rf.name,
                "table": ids.table(rf.table),
                "predicate": rf.predicate or None,
                "groups": rf.groups or ["*"],
                "source": " ".join(f"{rf.source_ref} {rf.source_expression}".split()) or bundle.tool,
            }
            if rf.todo:
                reasons = [f"TODO(unshackle): {r}" for r in todo_reasons(rf.todo)]
                item["todo"] = reasons[0] if len(reasons) == 1 else reasons
            rows.append({k: v for k, v in item.items() if v is not None})
        files[layout.rel("policies", f"row_filters.{slugify(bundle.tool)}.yml")] = dump_yaml({"row_filters": rows})
    return files


def load_row_filters(text: str) -> list[dict]:
    return (yaml.safe_load(text) or {}).get("row_filters", [])
